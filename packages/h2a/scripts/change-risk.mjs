function parseArgs(argv) {
  const opts = {
    mode: "diff",
    base: "origin/main",
    repo: process.cwd(),
    files: [],
    lcov: [],
    tests: [],
    exclude: [],
    top: 25,
    json: false,
    help: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--help" || a === "-h") opts.help = true;
    else if (a === "--all") opts.mode = "all";
    else if (a === "--json") opts.json = true;
    else if (a === "--base" && argv[i + 1]) opts.base = argv[++i];
    else if (a === "--repo" && argv[i + 1]) opts.repo = argv[++i];
    else if (a === "--top" && argv[i + 1]) opts.top = Number(argv[++i]);
    else if (a === "--lcov" && argv[i + 1]) opts.lcov.push(argv[++i]);
    else if (a === "--test" && argv[i + 1]) opts.tests.push(argv[++i]);
    else if (a === "--exclude" && argv[i + 1]) opts.exclude.push(argv[++i]);
    else if (a === "--file" && argv[i + 1]) {
      opts.files.push(argv[++i]);
      opts.mode = "files";
    } else if (!a.startsWith("-")) {
      opts.files.push(a);
      opts.mode = "files";
    } else {
      throw new Error(`unknown option: ${a}`);
    }
  }
  return opts;
}

function usageText() {
  return [
    "Usage: change-risk.mjs [options]",
    "  --base <ref>       Compare touched units against git ref (default: origin/main)",
    "  --all              Compute full repository inventory",
    "  --file <path>      Measure specific source file(s) (repeatable)",
    "  --test <path>      Run Node test file(s) with coverage (Level 1 turnkey, repeatable)",
    "  --lcov <path>      Read LCOV coverage file(s) (repeatable, merged)",
    "  --exclude <prefix> Exclude repo-relative path prefix (repeatable)",
    "  --repo <dir>       Repository root (default: cwd)",
    "  --top <n>          Number of rows shown in --all mode (default: 25)",
    "  --json             Emit JSON output",
    "  --help, -h         Show this help",
  ].join("\n") + "\n";
}

function summarizeRows(rows) {
  return {
    touched: rows.length,
    alerts: rows.filter((r) => r.alert).length,
    debt: rows.filter((r) => r.status === "debt").length,
    watch: rows.filter((r) => r.status === "watch").length,
    na: rows.filter((r) => r.status === "N-A").length,
    ok: rows.filter((r) => r.status === "ok").length,
  };
}

function runDiffMode(opts, ts, lcovMap, coverageInfo) {
  const absRoot = resolve(opts.repo);
  const diff = gitDiffText(absRoot, opts.base);
  const hunksByFile = parseGitDiffHunks(diff);
  const rows = [];
  const uncovered = [];

  for (const [relFile, ranges] of hunksByFile) {
    if (UNCOVERED_EXT_RE.test(relFile)) {
      if (!matchesPrefix(relFile, normalizePrefixes(opts.exclude))) uncovered.push(relFile);
      continue;
    }
    if (!isPathInPerimeter(relFile, { excludePrefixes: opts.exclude })) continue;
    const absFile = join(absRoot, relFile);
    if (!existsSync(absFile)) continue;
    const headText = readFileSync(absFile, "utf8");
    if (isGeneratedContent(headText)) continue;

    const headAnalysis = analyzeFileText(relFile, headText, ts);
    const baseText = gitReadFileAtRef(absRoot, opts.base, relFile);
    const baseMap = new Map();
    if (baseText !== null) {
      const baseAnalysis = analyzeFileText(relFile, baseText, ts);
      for (const u of baseAnalysis.activeUnits) baseMap.set(u.qname, u);
      if (!baseMap.has("<module>")) baseMap.set("<module>", baseAnalysis.moduleUnit);
    }

    for (const unit of headAnalysis.activeUnits) {
      if (!unitTouchesRanges(unit, ranges)) continue;
      const baseUnit = baseMap.get(unit.qname) ?? null;
      const baseCc = baseUnit ? baseUnit.ccCounted : null;
      rows.push(buildRow(unit, baseCc, lcovMap));
    }
  }

  const sorted = sortRowsWorstFirst(rows);
  const report = {
    mode: "diff",
    baseRef: opts.base,
    coverageSource: coverageInfo.source,
    vitestSkipped: coverageInfo.vitestSkipped,
    summary: summarizeRows(sorted),
    uncovered: uncovered.sort(),
    rows: sorted,
  };
  process.stdout.write(opts.json ? JSON.stringify(report, null, 2) + "\n" : formatDiffReport(report));
}

function runFilesMode(opts, ts, lcovMap, coverageInfo) {
  const absRoot = resolve(opts.repo);
  const rows = [];
  for (const rawFile of opts.files) {
    const absFile = resolve(absRoot, rawFile);
    const relFile = toPosix(relative(absRoot, absFile));
    const text = readFileSync(absFile, "utf8");
    const { activeUnits } = analyzeFileText(relFile, text, ts);
    for (const unit of activeUnits) {
      rows.push(buildRow(unit, unit.ccCounted, lcovMap));
    }
  }
  const sorted = sortRowsWorstFirst(rows);
  const report = {
    mode: "files",
    baseRef: "files",
    coverageSource: coverageInfo.source,
    vitestSkipped: coverageInfo.vitestSkipped,
    summary: summarizeRows(sorted),
    uncovered: [],
    rows: sorted,
  };
  process.stdout.write(opts.json ? JSON.stringify(report, null, 2) + "\n" : formatDiffReport(report));
}

function runAllMode(opts, ts, lcovMap, coverageInfo) {
  const absRoot = resolve(opts.repo);
  const perim = scanPerimeter(absRoot, { excludePrefixes: opts.exclude });
  const rows = [];
  let namedFunctions = 0;
  let moduleUnits = 0;
  let totalCases = 0;
  let delegatingCases = 0;

  for (const relFile of perim.kept) {
    const text = readFileSync(join(absRoot, relFile), "utf8");
    const analysis = analyzeFileText(relFile, text, ts);
    namedFunctions += analysis.units.length;
    if (analysis.moduleUnit.ccCounted >= 2) moduleUnits++;
    for (const unit of analysis.activeUnits) {
      totalCases += unit.totalCases;
      delegatingCases += unit.delegatingCases;
      rows.push(buildRow(unit, unit.ccCounted, lcovMap));
    }
  }

  const sorted = sortRowsWorstFirst(rows);
  const inventory = {
    filesAnalyzed: perim.kept.length,
    generatedSkipped: perim.generated.length,
    excludedSkipped: perim.excluded.length,
    uncoveredFiles: perim.uncovered,
    totalUnits: sorted.length,
    namedFunctions,
    moduleUnits,
    ccLe5: sorted.filter((r) => r.ccCounted <= 5).length,
    ccGe6: sorted.filter((r) => r.ccCounted >= 6).length,
    ccGe10: sorted.filter((r) => r.ccCounted >= 10).length,
    ccGe31: sorted.filter((r) => r.ccCounted >= 31).length,
    functionsGe31: sorted.filter((r) => r.kind === "function" && r.ccCounted >= 31).length,
    modulesGe31: sorted.filter((r) => r.kind === "module" && r.ccCounted >= 31).length,
    totalCases,
    delegatingCases,
  };

  const report = {
    mode: "all",
    repoRoot: absRoot,
    coverageSource: coverageInfo.source,
    vitestSkipped: coverageInfo.vitestSkipped,
    inventory,
    rows: sorted,
  };
  process.stdout.write(opts.json ? JSON.stringify(report, null, 2) + "\n" : formatAllReport(report, opts.top));
}

function collectCoverage(opts, rawArgv) {
  const absRoot = resolve(opts.repo);
  const lcovMaps = opts.lcov.map((p) => parseLcov(resolve(absRoot, p), absRoot));
  const vitestTests = opts.tests.filter((t) => isVitestFile(absRoot, t));
  const nodeTests = opts.tests.filter((t) => !isVitestFile(absRoot, t));

  if (needsSandboxReexec(absRoot, nodeTests)) {
    const code = runInsideSandbox(absRoot, rawArgv);
    process.exit(code);
  }

  if (nodeTests.length > 0) {
    lcovMaps.push(runNodeTestsWithCoverage(absRoot, nodeTests));
  }

  const merged = lcovMaps.length > 0 ? mergeLcovRecords(lcovMaps) : null;
  const parts = [];
  if (nodeTests.length > 0) parts.push(`targeted test (${nodeTests.join(", ")})`);
  if (opts.lcov.length > 0) parts.push(`LCOV (${opts.lcov.join(", ")})`);
  if (vitestTests.length > 0) parts.push(`Vitest N-A (${vitestTests.join(", ")})`);
  const source = parts.length > 0 ? parts.join(" + ") : "none (N-A — complexity only)";
  return { lcovMap: merged, coverageInfo: { source, vitestSkipped: vitestTests.length > 0 } };
}

export function main(rawArgv = process.argv.slice(2)) {
  const opts = parseArgs(rawArgv);
  if (opts.help) {
    process.stdout.write(usageText());
    return 0;
  }

  const ts = loadTypeScript(opts.repo);
  if (!ts) {
    process.stdout.write(
      `change-risk: typescript not found in ${resolve(opts.repo)}; skipping JS/TS analysis.\n`,
    );
    return 0;
  }

  const { lcovMap, coverageInfo } = collectCoverage(opts, rawArgv);

  if (opts.mode === "all") {
    runAllMode(opts, ts, lcovMap, coverageInfo);
  } else if (opts.mode === "files") {
    runFilesMode(opts, ts, lcovMap, coverageInfo);
  } else {
    runDiffMode(opts, ts, lcovMap, coverageInfo);
  }
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (err) {
    process.stderr.write(`change-risk: ${err.message}\n`);
    process.exitCode = 1;
  }
}

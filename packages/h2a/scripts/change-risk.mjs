function normalizeLcovFile(rawSf, repoRoot) {
  let target = rawSf.trim();
  if (target.startsWith("file://")) {
    try {
      target = fileURLToPath(target);
    } catch {
      // keep raw
    }
  }
  const abs = isAbsolute(target) ? target : resolve(repoRoot, target);
  return toPosix(relative(resolve(repoRoot), abs));
}

function pairFnRecords(fnList, fndaList) {
  if (fnList.length === fndaList.length && fnList.every((f, i) => f.name === fndaList[i].name)) {
    return fnList.map((f, i) => ({ line: f.line, name: f.name, hits: fndaList[i].hits }));
  }
  const byName = new Map();
  for (const item of fndaList) {
    const list = byName.get(item.name) ?? [];
    list.push(item.hits);
    byName.set(item.name, list);
  }
  return fnList.map((f) => {
    const queue = byName.get(f.name);
    const hits = queue && queue.length > 0 ? queue.shift() : null;
    return hits === null ? null : { line: f.line, name: f.name, hits };
  }).filter(Boolean);
}

function mergeFileRecord(target, block) {
  for (const [line, hits] of block.da) {
    target.da.set(line, (target.da.get(line) ?? 0) + hits);
  }
  const fnIndex = new Map(target.fns.map((f) => [`${f.line}\0${f.name}`, f]));
  for (const fn of block.fns) {
    const key = `${fn.line}\0${fn.name}`;
    const existing = fnIndex.get(key);
    if (existing) {
      existing.hits += fn.hits;
    } else {
      const copy = { ...fn };
      target.fns.push(copy);
      fnIndex.set(key, copy);
    }
  }
}

export function parseLcovText(text, repoRoot = process.cwd()) {
  const out = new Map();
  let cur = null;

  const flush = () => {
    if (!cur) return;
    const fns = pairFnRecords(cur.fn, cur.fnda);
    const existing = out.get(cur.sf) ?? { da: new Map(), fns: [] };
    mergeFileRecord(existing, { da: cur.da, fns });
    out.set(cur.sf, existing);
    cur = null;
  };

  for (const raw of text.split("\n")) {
    const line = raw.trim();
    if (line.startsWith("SF:")) {
      flush();
      cur = { sf: normalizeLcovFile(line.slice(3), repoRoot), da: new Map(), fn: [], fnda: [] };
    } else if (line === "end_of_record") {
      flush();
    } else if (!cur) {
      continue;
    } else if (line.startsWith("DA:")) {
      const [ln, hits] = line.slice(3).split(",");
      cur.da.set(Number(ln), Number(hits));
    } else if (line.startsWith("FN:")) {
      const idx = line.indexOf(",");
      if (idx > 3) cur.fn.push({ line: Number(line.slice(3, idx)), name: line.slice(idx + 1) });
    } else if (line.startsWith("FNDA:")) {
      const idx = line.indexOf(",");
      if (idx > 5) cur.fnda.push({ hits: Number(line.slice(5, idx)), name: line.slice(idx + 1) });
    }
  }
  flush();
  return out;
}

export function parseLcov(lcovPath, repoRoot = process.cwd()) {
  return parseLcovText(readFileSync(lcovPath, "utf8"), repoRoot);
}

export function mergeLcovRecords(maps) {
  const merged = new Map();
  for (const map of maps) {
    if (!map) continue;
    for (const [sf, rec] of map) {
      const target = merged.get(sf) ?? { da: new Map(), fns: [] };
      mergeFileRecord(target, rec);
      merged.set(sf, target);
    }
  }
  return merged;
}

function matchFnRecord(unit, rec) {
  const candidates = [unit.name];
  if (unit.name === "constructor" && unit.className) candidates.push(unit.className);

  let best = null;
  let bestDist = Infinity;
  for (const fn of rec.fns) {
    if (!candidates.includes(fn.name)) continue;
    const dist = Math.abs(fn.line - unit.start);
    if (dist > FN_LINE_TOLERANCE) continue;
    const betterTie = dist === bestDist && best !== null && fn.line <= unit.start && best.line > unit.start;
    if (dist < bestDist || betterTie) {
      best = fn;
      bestDist = dist;
    }
  }
  return best;
}

export function computeUnitCoverage(unit, rec) {
  if (!rec) return { cov: null, reason: "no-record", fn: null };

  // Rule 2: never called (FNDA:0) => 0% without consulting lines
  const fn = unit.kind === "function" ? matchFnRecord(unit, rec) : null;
  if (fn && fn.hits === 0) {
    return { cov: 0, reason: "FNDA:0", fn };
  }

  // Rule 1: own lines only (exclude nested named units' line ranges)
  let total = 0;
  let hit = 0;
  let firstHit = false;
  for (let line = unit.start; line <= unit.end; line++) {
    if (unit.children.some((c) => line >= c.start && line <= c.end)) continue;
    const count = rec.da.get(line);
    if (count === undefined) continue;
    total++;
    if (count > 0) {
      hit++;
      if (line === unit.start) firstHit = true;
    }
  }

  // Rule 5: nothing measurable => N-A
  if (total === 0) return { cov: null, reason: "no-lines", fn };

  // Rule 4: guard when no FN record matched and only declaration line is hit
  if (!fn && unit.kind === "function" && total >= 2 && hit === 1 && firstHit) {
    return { cov: 0, reason: "declaration-line-only", fn: null };
  }

  // Rule 3: fraction of own lines executed
  return { cov: hit / total, reason: fn ? "lines" : "lines-no-fn", fn };
}


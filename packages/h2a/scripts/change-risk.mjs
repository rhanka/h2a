// 4. AST analysis: units, cyclomatic complexity, delegating cases (NB-1, NB-2, B-2)
// ---------------------------------------------------------------------------

function isFnNode(n, ts) {
  return (
    ts.isFunctionDeclaration(n) ||
    ts.isMethodDeclaration(n) ||
    ts.isConstructorDeclaration(n) ||
    ts.isGetAccessorDeclaration(n) ||
    ts.isSetAccessorDeclaration(n) ||
    ts.isFunctionExpression(n) ||
    ts.isArrowFunction(n)
  );
}

function unwrapParent(p, ts) {
  let cur = p;
  while (
    cur &&
    (ts.isParenthesizedExpression(cur) ||
      ts.isAsExpression(cur) ||
      (typeof ts.isSatisfiesExpression === "function" && ts.isSatisfiesExpression(cur)))
  ) {
    cur = cur.parent;
  }
  return cur;
}

function isNamedFn(n, ts) {
  if (
    ts.isFunctionDeclaration(n) ||
    ts.isMethodDeclaration(n) ||
    ts.isConstructorDeclaration(n) ||
    ts.isGetAccessorDeclaration(n) ||
    ts.isSetAccessorDeclaration(n)
  ) {
    return true;
  }
  if (ts.isFunctionExpression(n) && n.name) return true;
  const p = unwrapParent(n.parent, ts);
  if (!p) return false;
  if (ts.isVariableDeclaration(p) || ts.isPropertyAssignment(p) || ts.isPropertyDeclaration(p)) {
    return true;
  }
  return ts.isBinaryExpression(p) && p.operatorToken.kind === ts.SyntaxKind.EqualsToken && p.right !== undefined;
}

function propNameText(nameNode, sf, ts) {
  return ts.isIdentifier(nameNode) ? nameNode.text : nameNode.getText(sf);
}

function getUnitName(node, sf, ts) {
  if (ts.isGetAccessorDeclaration(node)) return `get ${propNameText(node.name, sf, ts)}`;
  if (ts.isSetAccessorDeclaration(node)) return `set ${propNameText(node.name, sf, ts)}`;
  if (ts.isConstructorDeclaration(node)) return "constructor";
  if (node.name) return propNameText(node.name, sf, ts);
  if (ts.isFunctionDeclaration(node)) return "default";
  const p = unwrapParent(node.parent, ts);
  if (p && (ts.isVariableDeclaration(p) || ts.isPropertyAssignment(p) || ts.isPropertyDeclaration(p)) && p.name) {
    return p.name.getText(sf);
  }
  if (p && ts.isBinaryExpression(p) && p.operatorToken.kind === ts.SyntaxKind.EqualsToken) {
    return p.left.getText(sf);
  }
  if (p && ts.isExportAssignment(p)) return "default";
  return "<anonymous>";
}

function isCountedDecisionNode(n, ts) {
  const K = ts.SyntaxKind;
  switch (n.kind) {
    case K.IfStatement:
    case K.ForStatement:
    case K.ForInStatement:
    case K.ForOfStatement:
    case K.WhileStatement:
    case K.DoStatement:
    case K.CatchClause:
    case K.ConditionalExpression:
    case K.CaseClause:
      return true;
    case K.BinaryExpression: {
      const op = n.operatorToken.kind;
      return (
        op === K.AmpersandAmpersandToken ||
        op === K.BarBarToken ||
        op === K.AmpersandAmpersandEqualsToken ||
        op === K.BarBarEqualsToken
      );
    }
    default:
      return false;
  }
}

function subtreeHasLogic(node, ts) {
  let found = false;
  const visit = (c) => {
    if (found) return;
    if (isCountedDecisionNode(c, ts)) {
      found = true;
      return;
    }
    if (isFnNode(c, ts) && c.body && ts.isBlock(c.body)) {
      found = true;
      return;
    }
    ts.forEachChild(c, visit);
  };
  visit(node);
  return found;
}

function isTerminatorStatement(stmt, ts) {
  return (
    ts.isBreakStatement(stmt) ||
    ts.isContinueStatement(stmt) ||
    (ts.isReturnStatement(stmt) && !stmt.expression)
  );
}

function isPureCallExpression(expr, ts) {
  let cur = expr;
  while (
    cur &&
    (ts.isParenthesizedExpression(cur) ||
      ts.isAwaitExpression(cur) ||
      ts.isVoidExpression(cur))
  ) {
    cur = cur.expression;
  }
  return Boolean(cur && (ts.isCallExpression(cur) || ts.isNewExpression(cur)));
}

/**
 * Strict §4.6 / NB-1 delegating case body check:
 * - At most one useful statement: return, throw, or a direct call expression (never an assignment).
 * - Optionally followed by `break`, `continue`, or a bare `return`.
 * - Contains no counted decision and no block-bodied function.
 * - Empty body returns "empty" (inherits the clause it falls through into).
 */
function classifyCaseBody(statements, ts) {
  let st = statements;
  if (st.length === 1 && ts.isBlock(st[0])) st = st[0].statements;
  if (st.length === 0) return "empty";
  if (st.length > 2) return false;
  if (st.length === 1 && isTerminatorStatement(st[0], ts)) return true;
  if (st.length === 2 && !isTerminatorStatement(st[1], ts)) return false;

  const first = st[0];
  const allowedStatement =
    ts.isReturnStatement(first) ||
    ts.isThrowStatement(first) ||
    (ts.isExpressionStatement(first) && isPureCallExpression(first.expression, ts));
  if (!allowedStatement) return false;
  return !subtreeHasLogic(first, ts);
}

function delegatingCasesOfSwitch(switchNode, ts) {
  const clauses = switchNode.caseBlock.clauses;
  const delegating = new Set();
  let carry = false;
  for (let i = clauses.length - 1; i >= 0; i--) {
    const clause = clauses[i];
    const kind = classifyCaseBody(clause.statements, ts);
    if (kind === "empty") {
      if (carry && ts.isCaseClause(clause)) delegating.add(clause);
      continue;
    }
    carry = kind === true;
    if (carry && ts.isCaseClause(clause)) delegating.add(clause);
  }
  return delegating;
}

function countDecisions(root, ts) {
  let classic = 0;
  let totalCases = 0;
  let delegatingCases = 0;
  const delegatingSet = new Set();

  const visit = (n) => {
    if (ts.isSwitchStatement(n)) {
      for (const c of delegatingCasesOfSwitch(n, ts)) delegatingSet.add(c);
    } else if (ts.isCaseClause(n)) {
      classic++;
      totalCases++;
      if (delegatingSet.has(n)) delegatingCases++;
    } else if (isCountedDecisionNode(n, ts)) {
      classic++;
    }
    ts.forEachChild(n, (child) => {
      if (isFnNode(child, ts) && child.body && isNamedFn(child, ts)) return;
      visit(child);
    });
  };

  ts.forEachChild(root, (child) => {
    if (isFnNode(child, ts) && child.body && isNamedFn(child, ts)) return;
    visit(child);
  });

  const ccClassic = 1 + classic;
  const ccCounted = ccClassic - delegatingCases;
  return { ccClassic, ccCounted, totalCases, delegatingCases };
}

function scriptKindFor(filePath, ts) {
  if (/\.tsx$/.test(filePath)) return ts.ScriptKind.TSX;
  if (/\.jsx$/.test(filePath)) return ts.ScriptKind.JSX;
  if (/\.[cm]?js$/.test(filePath)) return ts.ScriptKind.JS;
  return ts.ScriptKind.TS;
}

export function analyzeFileText(relPath, text, ts) {
  const normFile = toPosix(relPath);
  const sf = ts.createSourceFile(normFile, text, ts.ScriptTarget.Latest, true, scriptKindFor(normFile, ts));
  const lineOf = (pos) => sf.getLineAndCharacterOfPosition(pos).line + 1;

  const moduleUnit = {
    file: normFile,
    name: "<module>",
    qname: "<module>",
    className: null,
    kind: "module",
    start: 1,
    end: lineOf(sf.getEnd()),
    children: [],
    ...countDecisions(sf, ts),
  };

  const units = [];
  const visit = (node, owner, qual, currentClass) => {
    if (isFnNode(node, ts) && node.body) {
      if (isNamedFn(node, ts)) {
        const name = getUnitName(node, sf, ts);
        const unit = {
          file: normFile,
          name,
          qname: [...qual, name].join("."),
          className: ts.isConstructorDeclaration(node) ? currentClass : null,
          kind: "function",
          start: lineOf(node.getStart(sf)),
          end: lineOf(node.getEnd()),
          children: [],
          ...countDecisions(node, ts),
        };
        owner.children.push(unit);
        units.push(unit);
        ts.forEachChild(node, (c) => visit(c, unit, [...qual, name], currentClass));
        return;
      }
      ts.forEachChild(node, (c) => visit(c, owner, qual, currentClass));
      return;
    }

    const isNamedClass = (ts.isClassDeclaration(node) || ts.isClassExpression(node)) && node.name;
    const nextQual = isNamedClass ? [...qual, node.name.text] : qual;
    const nextClass = isNamedClass ? node.name.text : currentClass;
    ts.forEachChild(node, (c) => visit(c, owner, nextQual, nextClass));
  };

  visit(sf, moduleUnit, [], null);

  const activeUnits = moduleUnit.ccCounted >= 2 ? [...units, moduleUnit] : [...units];
  return { units, moduleUnit, activeUnits };
}


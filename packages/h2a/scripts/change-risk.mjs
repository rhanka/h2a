export function parseGitDiffHunks(diffText) {
  const byFile = new Map();
  let curFile = null;
  for (const line of diffText.split("\n")) {
    if (line.startsWith("+++ b/")) {
      curFile = toPosix(line.slice(6).trim());
      if (!byFile.has(curFile)) byFile.set(curFile, []);
    } else if (line.startsWith("+++ /dev/null")) {
      curFile = null;
    } else if (curFile && line.startsWith("@@ ")) {
      const m = line.match(/\+(\d+)(?:,(\d+))?/);
      if (!m) continue;
      const start = Number(m[1]);
      const count = m[2] === undefined ? 1 : Number(m[2]);
      const end = count === 0 ? start : start + count - 1;
      byFile.get(curFile).push([start, end]);
    }
  }
  return byFile;
}

function unitTouchesRanges(unit, ranges) {
  for (const [a, b] of ranges) {
    const lo = Math.max(unit.start, a);
    const hi = Math.min(unit.end, b);
    for (let line = lo; line <= hi; line++) {
      if (!unit.children.some((c) => line >= c.start && line <= c.end)) {
        return true;
      }
    }
  }
  return false;
}

function gitReadFileAtRef(repoRoot, ref, relPath) {
  const res = spawnSync("git", ["show", `${ref}:${relPath}`], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  return res.status === 0 ? res.stdout : null;
}

function gitDiffText(repoRoot, baseRef) {
  const res = spawnSync("git", ["diff", "-U0", "--diff-filter=ACMR", baseRef], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 32 * 1024 * 1024,
  });
  if (res.status !== 0) {
    throw new Error(`git diff failed for base "${baseRef}": ${res.stderr.trim()}`);
  }
  return res.stdout;
}


function isVitestFile(repoRoot, testPath) {
  const norm = toPosix(testPath);
  if (/\.(test|spec)\.tsx?$/.test(norm)) return true;
  const abs = resolve(repoRoot, testPath);
  if (!existsSync(abs)) return false;
  const head = readFileSync(abs, "utf8").slice(0, 1024);
  return /\bfrom\s+["']vitest["']/.test(head) || /\brequire\(["']vitest["']\)/.test(head);
}

function makeWritableWorkdir(repoRoot) {
  if (process.env[TEST_STATE_BARRIER_ENV] === "1" && process.env.TMPDIR) {
    try {
      mkdirSync(process.env.TMPDIR, { recursive: true });
      return mkdtempSync(join(process.env.TMPDIR, "change-risk-"));
    } catch {
      // TMPDIR may be read-only; fall through to repo-local tmp/
    }
  }
  const repoTmp = join(resolve(repoRoot), "tmp");
  try {
    mkdirSync(repoTmp, { recursive: true });
    return mkdtempSync(join(repoTmp, "change-risk-"));
  } catch {
    const fallback = process.env.TMPDIR || repoTmp;
    mkdirSync(fallback, { recursive: true });
    return mkdtempSync(join(fallback, "change-risk-"));
  }
}

function needsSandboxReexec(repoRoot, nodeTests) {
  if (nodeTests.length === 0) return false;
  if (process.env[TEST_STATE_BARRIER_ENV] === "1") return false;
  return existsSync(join(resolve(repoRoot), "scripts", "test-sandbox.mjs"));
}

function sanitizeSubtestEnv(workdir) {
  const env = { ...process.env, TMPDIR: workdir, TMP: workdir, TEMP: workdir };
  delete env.NODE_TEST_CONTEXT;
  delete env.NODE_V8_COVERAGE;
  return env;
}

function runInsideSandbox(repoRoot, rawArgv) {
  const absRoot = resolve(repoRoot);
  const sandboxScript = join(absRoot, "scripts", "test-sandbox.mjs");
  const thisScript = fileURLToPath(import.meta.url);
  const stageDir = makeWritableWorkdir(absRoot);
  try {
    const res = spawnSync(
      process.execPath,
      [sandboxScript, "--", process.execPath, thisScript, ...rawArgv],
      {
        cwd: absRoot,
        stdio: "inherit",
        env: sanitizeSubtestEnv(stageDir),
      },
    );
    return res.status ?? 1;
  } finally {
    rmSync(stageDir, { recursive: true, force: true });
  }
}

function runNodeTestsWithCoverage(repoRoot, testFiles) {
  const absRoot = resolve(repoRoot);
  const workdir = makeWritableWorkdir(absRoot);
  try {
    const lcovPath = join(workdir, "coverage.lcov");
    const nativeIsolation = join(absRoot, "packages", "h2a", "test", "helpers", "native-isolation.js");
    const needsNativeIsolation =
      existsSync(nativeIsolation) &&
      testFiles.some((f) => {
        const rel = toPosix(relative(absRoot, resolve(absRoot, f)));
        return rel.startsWith("packages/h2a/test/") && rel.endsWith(".test.js");
      });

    const nodeArgs = [
      "--enable-source-maps",
      "--experimental-test-coverage",
      ...(needsNativeIsolation ? ["--import", nativeIsolation] : []),
      "--test",
      "--test-reporter=lcov",
      `--test-reporter-destination=${lcovPath}`,
      "--test-reporter=spec",
      "--test-reporter-destination=stderr",
      ...testFiles.map((f) => resolve(absRoot, f)),
    ];

    const res = spawnSync(process.execPath, nodeArgs, {
      cwd: absRoot,
      encoding: "utf8",
      env: sanitizeSubtestEnv(workdir),
      maxBuffer: 32 * 1024 * 1024,
    });

    if (res.status !== 0) {
      const detail = (res.stderr || res.stdout || "").trim();
      throw new Error(`targeted test failed (exit ${res.status}):\n${detail}`);
    }
    if (!existsSync(lcovPath)) {
      return new Map();
    }
    return parseLcov(lcovPath, absRoot);
  } finally {
    rmSync(workdir, { recursive: true, force: true });
  }
}


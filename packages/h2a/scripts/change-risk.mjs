function buildRow(unit, baseCc, lcovMap) {
  const rec = lcovMap ? lcovMap.get(unit.file) : null;
  const covInfo = computeUnitCoverage(unit, rec);
  const verdict = classifyUnit({ ccCounted: unit.ccCounted, baseCc, cov: covInfo.cov });
  const minCov = minCoverageForThreshold(unit.ccCounted);
  return {
    file: unit.file,
    qname: unit.qname,
    kind: unit.kind,
    start: unit.start,
    end: unit.end,
    lines: unit.end - unit.start + 1,
    ccClassic: unit.ccClassic,
    ccCounted: unit.ccCounted,
    delegatingCases: unit.delegatingCases,
    totalCases: unit.totalCases,
    baseCc,
    cov: covInfo.cov,
    covReason: covInfo.reason,
    fnda: covInfo.fn ? covInfo.fn.hits : null,
    score: verdict.score,
    status: verdict.status,
    alert: verdict.alert,
    minCoverage: minCov,
  };
}

function sortRowsWorstFirst(rows) {
  return [...rows].sort((a, b) => {
    const sa = a.score ?? (a.ccCounted > THRESHOLD_MAX ? a.ccCounted * 1000 : a.ccCounted);
    const sb = b.score ?? (b.ccCounted > THRESHOLD_MAX ? b.ccCounted * 1000 : b.ccCounted);
    if (sb !== sa) return sb - sa;
    if (b.ccCounted !== a.ccCounted) return b.ccCounted - a.ccCounted;
    return a.file.localeCompare(b.file) || a.start - b.start;
  });
}

function formatComplexity(row) {
  return row.delegatingCases > 0 ? `${row.ccCounted} (${row.ccClassic})` : String(row.ccCounted);
}

function formatDelta(row) {
  return row.baseCc === null ? "new" : `${row.baseCc}->${row.ccCounted}`;
}

function formatCoverage(row) {
  if (row.cov === null) return "N-A";
  return `${Math.round(row.cov * 100)} %`;
}

function formatScore(row) {
  return row.score === null ? "N-A" : row.score.toFixed(1);
}

function padCols(rows, headers) {
  const widths = headers.map((h, i) => Math.max(h.length, ...rows.map((r) => r[i].length)));
  const render = (cols) => cols.map((c, i) => (i === cols.length - 1 ? c : c.padEnd(widths[i]))).join("  ");
  return [render(headers), ...rows.map(render)].join("\n");
}

function formatActionLine(rows) {
  const alerts = rows.filter((r) => r.alert);
  if (alerts.length > 0) {
    const worst = alerts[0];
    if (worst.minCoverage === null) {
      return `Action: TO FIX: ${worst.qname} (complexity ${worst.ccCounted} > ${THRESHOLD_MAX}; tests alone cannot bring score <= ${THRESHOLD_MAX} — pin behaviour with tests first, then split or extract delegating cases).`;
    }
    const pct = Math.ceil(worst.minCoverage * 100);
    return `Action: TO FIX: ${worst.qname} (complexity ${worst.ccCounted}, ${formatCoverage(worst)} coverage; >= ${pct} % coverage brings score to <= ${THRESHOLD_MAX}).`;
  }
  const naNeedingCov = rows.filter((r) => r.status === "N-A" && r.minCoverage !== null);
  if (naNeedingCov.length > 0) {
    const worst = naNeedingCov[0];
    const pct = Math.ceil(worst.minCoverage * 100);
    return `Action: coverage N-A for ${worst.qname} (complexity ${worst.ccCounted}); >= ${pct} % coverage needed for score <= ${THRESHOLD_MAX}. Run with --test <file> to measure.`;
  }
  const debt = rows.filter((r) => r.status === "debt");
  if (debt.length > 0) {
    return `Action: ${debt.length} pre-existing debt unit(s) untouched in complexity (reported and left; handled via harness/code-debt).`;
  }
  return "Action: all measured units are within threshold.";
}

function formatDiffReport(report) {
  const lines = [];
  lines.push(`Change risk (CRAP) — touched units (base ${report.baseRef})`);
  lines.push(`Threshold: > ${THRESHOLD_MAX} TO FIX (added/increased) | debt (pre-existing) | ${THRESHOLD_WATCH}–${THRESHOLD_MAX} watch | <= ${THRESHOLD_WATCH} ok`);
  lines.push(`Coverage: ${report.coverageSource}`);
  if (report.vitestSkipped) {
    lines.push("Note: Vitest coverage is not yet configured (planned for Lot 4); showing complexity-only results (N-A).");
  }
  lines.push("");

  if (report.rows.length === 0) {
    lines.push("No JS/TS units touched in perimeter.");
  } else {
    const headers = ["score", "complexity", "delta", "coverage", "status", "unit", "location"];
    const tableRows = report.rows.map((r) => [
      formatScore(r),
      formatComplexity(r),
      formatDelta(r),
      formatCoverage(r),
      r.status,
      r.qname,
      `${r.file}:${r.start}`,
    ]);
    lines.push(padCols(tableRows, headers));
  }

  lines.push("");
  const s = report.summary;
  lines.push(`Summary: ${s.touched} touched | ${s.alerts} alert(s) | ${s.debt} debt | ${s.watch} watch | ${s.na} N-A | ${s.ok} ok`);
  if (report.rows.length > 0) lines.push(formatActionLine(report.rows));
  if (report.uncovered.length > 0) {
    lines.push(`Uncovered touched files (${report.uncovered.length}): ${report.uncovered.join(", ")}`);
  }
  return lines.join("\n") + "\n";
}

function formatAllReport(report, topN) {
  const lines = [];
  lines.push(`Change risk (CRAP) — repository inventory (${report.repoRoot})`);
  lines.push(`Coverage: ${report.coverageSource}`);
  if (report.vitestSkipped) {
    lines.push("Note: Vitest coverage is not yet configured (planned for Lot 4); showing complexity-only results (N-A).");
  }
  lines.push("");
  const s = report.inventory;
  lines.push(
    `Files: ${s.filesAnalyzed} JS/TS analyzed | ${s.generatedSkipped} generated skipped | ${s.excludedSkipped} excluded | ${s.uncoveredFiles.length} uncovered`,
  );
  lines.push(
    `Units: ${s.totalUnits} total (${s.namedFunctions} named functions + ${s.moduleUnits} <module> with CC >= 2)`,
  );
  lines.push(
    `Counted complexity: ${s.ccLe5} (<=5) | ${s.ccGe6} (>=6) | ${s.ccGe10} (>=10) | ${s.ccGe31} (>=31 debt: ${s.functionsGe31} functions + ${s.modulesGe31} <module>)`,
  );
  lines.push(`Switch cases: ${s.totalCases} total, ${s.delegatingCases} delegating (exempted)`);
  lines.push("");

  const shown = report.rows.slice(0, topN);
  if (shown.length > 0) {
    lines.push(`Top ${shown.length} units (worst first):`);
    const headers = ["score", "complexity", "coverage", "status", "unit", "location"];
    const tableRows = shown.map((r) => [
      formatScore(r),
      formatComplexity(r),
      formatCoverage(r),
      r.status,
      r.qname,
      `${r.file}:${r.start}`,
    ]);
    lines.push(padCols(tableRows, headers));
  }

  if (s.uncoveredFiles.length > 0) {
    lines.push("");
    lines.push(`Uncovered files (${s.uncoveredFiles.length}, not parsed by TypeScript):`);
    for (const f of s.uncoveredFiles) lines.push(`  - ${f}`);
  }
  return lines.join("\n") + "\n";
}


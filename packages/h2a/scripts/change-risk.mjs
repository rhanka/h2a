#!/usr/bin/env node
/**
 * Change-risk (CRAP) score tool for JS/TS repositories.
 *
 * Pure Node + repository-local `typescript` (loaded via createRequire). Zero Python.
 *
 * Usage:
 *   npm run crap                                            # diff vs origin/main (Level 0)
 *   npm run crap -- --base origin/main                      # diff vs ref (Level 0)
 *   npm run crap -- --test <node-test-file> [...]           # diff + targeted coverage (Level 1)
 *   npm run crap -- --lcov <path> [...] [--base <ref>]      # diff + existing LCOV
 *   npm run crap -- --all [--lcov <path>] [--top <n>]       # whole-repo inventory
 *   npm run crap -- --file <path> [...] [--test ...|--lcov] # specific source files
 *   Options: --repo <dir> --exclude <prefix> --json --help
 */
import { spawnSync } from "node:child_process";
import {
  existsSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readdirSync,
  rmSync,
} from "node:fs";
import { createRequire } from "node:module";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const THRESHOLD_MAX = 30;
export const THRESHOLD_WATCH = 10;
export const FN_LINE_TOLERANCE = 3;

const TEST_STATE_BARRIER_ENV = "H2A_TEST_STATE_BARRIER";

const SKIP_DIRS = new Set([
  "node_modules",
  "dist",
  "build",
  "vendor",
  "focus-vendor",
  "fixtures",
  ".test-scratch",
  "focus-app",
  ".svelte-kit",
  "coverage",
  "tmp",
  ".tmp",
  ".git",
  "test",
  "tests",
  "__tests__",
]);

const SRC_EXT_RE = /\.(ts|tsx|mts|cts|js|mjs|cjs)$/;
const DTS_RE = /\.d\.[cm]?ts$/;
const TEST_FILE_RE = /\.(test|spec)\.[cm]?[jt]sx?$/;
const UNCOVERED_EXT_RE = /\.(svelte|vue)$/;
const GENERATED_RE = /GENERATED|Generated by|DO NOT EDIT/;

const toPosix = (p) => p.replaceAll("\\", "/");

// ---------------------------------------------------------------------------
// 1. Dynamic TypeScript resolution (NB-5: resolve from target repo first)
// ---------------------------------------------------------------------------

export function loadTypeScript(repoRoot = process.cwd()) {
  try {
    const req = createRequire(resolve(repoRoot, "package.json"));
    return req("typescript");
  } catch {
    return null;
  }
}

// ---------------------------------------------------------------------------
// 2. Formula, thresholds, and classification (Owner Q1 = C)
// ---------------------------------------------------------------------------

export function crapScore(complexity, coverage) {
  return complexity * complexity * Math.pow(1 - coverage, 3) + complexity;
}

export function minCoverageForThreshold(complexity, threshold = THRESHOLD_MAX) {
  if (complexity <= 0) return 0;
  if (complexity * complexity + complexity <= threshold) return 0;
  if (complexity > threshold) return null;
  return 1 - Math.cbrt((threshold - complexity) / (complexity * complexity));
}

export function classifyUnit({ ccCounted, baseCc, cov }) {
  const ratchetArmed = baseCc === null || ccCounted > baseCc;
  if (cov === null) {
    if (ccCounted > THRESHOLD_MAX) {
      return { score: null, status: ratchetArmed ? "TO FIX" : "debt", alert: ratchetArmed };
    }
    if (ccCounted <= 5) {
      return { score: null, status: "ok", alert: false };
    }
    return { score: null, status: "N-A", alert: false };
  }

  const score = crapScore(ccCounted, cov);
  if (score > THRESHOLD_MAX) {
    return { score, status: ratchetArmed ? "TO FIX" : "debt", alert: ratchetArmed };
  }
  if (score > THRESHOLD_WATCH) {
    return { score, status: "watch", alert: false };
  }
  return { score, status: "ok", alert: false };
}

// ---------------------------------------------------------------------------
// 3. Perimeter scanning (NB-3, D16)
// ---------------------------------------------------------------------------

function normalizePrefixes(prefixes = []) {
  return prefixes
    .map((p) => toPosix(p).replace(/^\/+|\/+$/g, ""))
    .filter(Boolean);
}

function matchesPrefix(relPosix, prefixes) {
  return prefixes.some((pref) => relPosix === pref || relPosix.startsWith(`${pref}/`));
}

export function isSourceFilename(name) {
  return SRC_EXT_RE.test(name) && !DTS_RE.test(name) && !TEST_FILE_RE.test(name);
}

export function isGeneratedContent(text) {
  return GENERATED_RE.test(text.slice(0, 400));
}

export function isPathInPerimeter(relPath, { excludePrefixes = [] } = {}) {
  const norm = toPosix(relPath).replace(/^\.\//, "");
  const parts = norm.split("/");
  if (parts.slice(0, -1).some((seg) => SKIP_DIRS.has(seg))) return false;
  if (matchesPrefix(norm, normalizePrefixes(excludePrefixes))) return false;
  return isSourceFilename(parts[parts.length - 1]);
}

export function scanPerimeter(repoRoot, { excludePrefixes = [] } = {}) {
  const absRoot = resolve(repoRoot);
  const prefixes = normalizePrefixes(excludePrefixes);
  const out = { kept: [], generated: [], uncovered: [], excluded: [] };

  const walk = (dir) => {
    let entries;
    try {
      entries = readdirSync(dir);
    } catch {
      return;
    }
    for (const name of entries) {
      const full = join(dir, name);
      let st;
      try {
        st = lstatSync(full);
      } catch {
        continue;
      }
      if (st.isSymbolicLink()) continue;
      const rel = toPosix(relative(absRoot, full));
      if (st.isDirectory()) {
        if (!SKIP_DIRS.has(name)) walk(full);
        continue;
      }
      if (!st.isFile()) continue;
      if (UNCOVERED_EXT_RE.test(name)) {
        if (!matchesPrefix(rel, prefixes)) out.uncovered.push(rel);
        continue;
      }
      if (!isSourceFilename(name)) continue;
      if (matchesPrefix(rel, prefixes)) {
        out.excluded.push(rel);
        continue;
      }
      const head = readFileSync(full, "utf8");
      if (isGeneratedContent(head)) {
        out.generated.push(rel);
      } else {
        out.kept.push(rel);
      }
    }
  };

  walk(absRoot);
  out.kept.sort();
  out.generated.sort();
  out.uncovered.sort();
  out.excluded.sort();
  return out;
}


import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { fileURLToPath } from "node:url";

const AUDIT_CLI = fileURLToPath(
  new URL("./audit-commit-identity.mjs", import.meta.url),
);

function makeSandbox(t, prefix = "audit-identity-") {
  const dir = mkdtempSync(join(tmpdir(), prefix));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  return dir;
}

function git(cwd, args, extraEnv = {}) {
  return execFileSync("git", ["-C", cwd, ...args], {
    encoding: "utf8",
    env: {
      ...process.env,
      GIT_CONFIG_GLOBAL: "/dev/null",
      GIT_CONFIG_SYSTEM: "/dev/null",
      ...extraEnv,
    },
  }).trim();
}

function commitFile(repo, filename, content, message, env = {}) {
  writeFileSync(join(repo, filename), content);
  git(repo, ["add", filename]);
  git(repo, ["commit", "-q", "--no-verify", "-m", message], env);
  return git(repo, ["rev-parse", "HEAD"]);
}

test("audit-commit-identity.mjs reports per-repo and per-ref violations read-only", (t) => {
  const dir = makeSandbox(t);
  const repo = join(dir, "sample-repo");
  mkdirSync(repo, { recursive: true });
  git(repo, ["init", "-q", "-b", "main"]);
  git(repo, ["config", "user.name", "Fabien Antoine"]);
  git(repo, ["config", "user.email", "fabien.antoine@m4x.org"]);

  const clean1 = commitFile(repo, "a.txt", "1\n", "chore: clean init\n\n🤖 emoji only");
  // Alternate owner name with valid email: compliant (0 violations), 1 informational nameMismatch.
  const altNameOk = commitFile(repo, "alt.txt", "alt\n", "chore: alt owner name", {
    GIT_AUTHOR_NAME: "rhanka",
    GIT_AUTHOR_EMAIL: "fabien.antoine@m4x.org",
    GIT_COMMITTER_NAME: "antoinefa",
    GIT_COMMITTER_EMAIL: "fabien.antoine@m4x.org",
  });
  const badHumanCoauthor = commitFile(
    repo,
    "b.txt",
    "2\n",
    "feat: coauthor\n\nCo-Authored-By: Alice Martin <alice@example.com>",
  );
  // GitHub squash Co-authored-by trailer (explicitly tracked).
  const badGithubSquashCoauthor = commitFile(
    repo,
    "b2.txt",
    "2b\n",
    "feat: squash\n\nCo-authored-by: Fabien Antoine <antoinefa@users.noreply.github.com>",
  );
  const badAiAttr = commitFile(
    repo,
    "c.txt",
    "3\n",
    "feat: ai\n\nGenerated by Claude Opus 4.8\nContact: noreply@anthropic.com",
  );
  const badAuthor = commitFile(repo, "d.txt", "4\n", "chore(deps): bump foo", {
    GIT_AUTHOR_NAME: "dependabot[bot]",
    GIT_AUTHOR_EMAIL: "49699333+dependabot[bot]@users.noreply.github.com",
    GIT_COMMITTER_NAME: "GitHub",
    GIT_COMMITTER_EMAIL: "noreply@github.com",
  });
  const badUpstream = commitFile(repo, "u.txt", "u\n", "feat: upstream fork commit", {
    GIT_AUTHOR_NAME: "Upstream Dev",
    GIT_AUTHOR_EMAIL: "upstream-dev@example.com",
    GIT_COMMITTER_NAME: "Upstream Dev",
    GIT_COMMITTER_EMAIL: "upstream-dev@example.com",
  });
  const badLocal = commitFile(repo, "l.txt", "l\n", "feat: lane commit", {
    GIT_AUTHOR_NAME: "Lane",
    GIT_AUTHOR_EMAIL: "lane@localhost",
    GIT_COMMITTER_NAME: "Lane",
    GIT_COMMITTER_EMAIL: "lane@localhost",
  });

  // Create a clean branch from clean1 + a GitHub web-flow merge commit (2 parents, owner author).
  git(repo, ["checkout", "-q", "-b", "clean-branch", clean1]);
  commitFile(repo, "e.txt", "5\n", "feat: clean side");
  git(repo, ["checkout", "-q", "-b", "merge-branch", clean1]);
  commitFile(repo, "f.txt", "6\n", "feat: clean base");
  git(repo, ["merge", "-q", "--no-ff", "--no-verify", "-m", "Merge pull request #1 from rhanka/clean-branch", "clean-branch"], {
    GIT_COMMITTER_NAME: "GitHub",
    GIT_COMMITTER_EMAIL: "noreply@github.com",
  });
  const mergeSha = git(repo, ["rev-parse", "HEAD"]);

  // Fake remote tracking ref origin/main pointing to main.
  const mainSha = git(repo, ["rev-parse", "main"]);
  git(repo, ["update-ref", "refs/remotes/origin/main", mainSha]);
  git(repo, ["symbolic-ref", "refs/remotes/origin/HEAD", "refs/remotes/origin/main"]);

  const headBefore = git(repo, ["rev-parse", "HEAD"]);
  const statusBefore = git(repo, ["status", "--porcelain"]);
  const mdPath = join(dir, "AUDIT.md");

  const run = spawnSync(
    process.execPath,
    [AUDIT_CLI, "--json", "--markdown", mdPath, repo],
    { encoding: "utf8" },
  );
  assert.equal(run.status, 0, run.stderr);

  // Strictly read-only: HEAD and status untouched.
  assert.equal(git(repo, ["rev-parse", "HEAD"]), headBefore);
  assert.equal(git(repo, ["status", "--porcelain"]), statusBefore);

  const report = JSON.parse(run.stdout);
  assert.equal(report.repos.length, 1);
  const r = report.repos[0];
  // 6 violating commits: badHumanCoauthor, badGithubSquashCoauthor, badAiAttr, badAuthor, badUpstream, badLocal.
  // altNameOk is NOT a violation (email is valid), only an informational nameMismatch!
  assert.equal(r.uniqueViolatingCommits, 6);
  assert.equal(r.uniqueNameMismatches, 1);
  assert.equal(r.uniqueCounts.githubSquashCoAuthor, 1);

  const upstreamEntry = r.badEmailBreakdown.find((e) => e.email === "upstream-dev@example.com");
  assert.ok(upstreamEntry, "upstream email present in breakdown");
  assert.equal(upstreamEntry.category, "UPSTREAM");

  const localEntry = r.badEmailBreakdown.find((e) => e.email === "lane@localhost");
  assert.ok(localEntry, "local agent email present in breakdown");
  assert.equal(localEntry.category, "LOCAL_AGENT");

  const botEntry = r.badEmailBreakdown.find((e) => e.email.includes("dependabot"));
  assert.ok(botEntry, "bot email present in breakdown");
  assert.equal(botEntry.category, "BOT");

  const mainRef = r.refs.find((ref) => ref.ref === "main");
  assert.ok(mainRef, "local main ref present");
  assert.equal(mainRef.violatingCommits, 6);
  assert.equal(mainRef.nameMismatches, 1);
  assert.equal(mainRef.counts.coAuthoredBy, 2);
  assert.equal(mainRef.counts.githubSquashCoAuthor, 1);
  assert.equal(mainRef.counts.aiAttribution, 1);
  assert.equal(mainRef.counts.badIdentity, 3);
  assert.ok(mainRef.exampleShas.includes(badLocal.slice(0, 10)));
  assert.ok(mainRef.exampleShas.includes(badUpstream.slice(0, 10)));
  assert.ok(mainRef.exampleShas.includes(badAuthor.slice(0, 10)));
  assert.equal(mainRef.exampleShas.includes(altNameOk.slice(0, 10)), false);

  const originMainRef = r.refs.find((ref) => ref.ref === "origin/main");
  assert.ok(originMainRef, "origin/main ref present");
  assert.equal(originMainRef.violatingCommits, 6);
  assert.equal(
    r.refs.some((ref) => ref.ref === "origin/HEAD"),
    false,
    "symbolic origin/HEAD skipped",
  );

  // Per-repo --require-name "Fabien Antoine" turns altNameOk into a violation (7 total).
  const reqNameRun = spawnSync(
    process.execPath,
    [AUDIT_CLI, "--require-name", "Fabien Antoine", "--json", repo],
    { encoding: "utf8" },
  );
  assert.equal(reqNameRun.status, 0, reqNameRun.stderr);
  const reqNameReport = JSON.parse(reqNameRun.stdout);
  assert.equal(reqNameReport.repos[0].uniqueViolatingCommits, 7);

  const cleanRef = r.refs.find((ref) => ref.ref === "clean-branch");
  assert.equal(cleanRef.violatingCommits, 0);

  // Historical unsigned GitHub merge by owner passes default audit, fails --strict-webflow-sig.
  const mergeRef = r.refs.find((ref) => ref.ref === "merge-branch");
  assert.equal(mergeRef.violatingCommits, 0);
  assert.equal(mergeRef.unsignedGithubMerges, 1);

  const strictRun = spawnSync(
    process.execPath,
    [AUDIT_CLI, "--strict-webflow-sig", "--json", repo],
    { encoding: "utf8" },
  );
  assert.equal(strictRun.status, 0, strictRun.stderr);
  const strictReport = JSON.parse(strictRun.stdout);
  const strictMergeRef = strictReport.repos[0].refs.find((ref) => ref.ref === "merge-branch");
  assert.equal(strictMergeRef.violatingCommits, 1);
  assert.ok(strictMergeRef.exampleShas.includes(mergeSha.slice(0, 10)));

  const md = readFileSync(mdPath, "utf8");
  assert.match(md, /sample-repo/);
  assert.match(md, /origin\/main/);
  assert.match(md, /UPSTREAM/);
  assert.match(md, /Écart nom|name-mismatch/i);
  assert.match(md, new RegExp(badAuthor.slice(0, 10)));
});

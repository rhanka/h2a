#!/usr/bin/env node
// CI-only release preparation and promotion proof. No registry writes here.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { appendFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { isDeepStrictEqual } from 'node:util'
import { checkLockstepVersions } from './check-lockstep-versions.mjs'
import { checkPluginContentVersionBump } from './check-plugin-version.mjs'

const names = ['track', 'h2a-runtime', 'h2a', 'h2a-cli']
const triple = '(0|[1-9]\\d*)\\.(0|[1-9]\\d*)\\.(0|[1-9]\\d*)'
const tag = process.env.BACKFILL_VERSION ? `v${process.env.BACKFILL_VERSION}` : process.env.GITHUB_REF?.replace(/^refs\/tags\//, '')
if (process.env.GITHUB_ACTIONS !== 'true' || !new RegExp(`^v${triple}(-rc\\.(0|[1-9]\\d*))?$`).test(tag ?? '')) {
  throw new Error('release-candidate requires GitHub Actions and a vX.Y.Z or vX.Y.Z-rc.N tag')
}
const version = tag.slice(1), base = version.split('-')[0], rc = version !== base
const command = (bin, args) => execFileSync(bin, args, { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }).trim()
const tree = () => command('git', ['rev-parse', 'HEAD^{tree}'])
const repository = process.env.GITHUB_REPOSITORY
// Focus joins the release wave, but keeps its own stable version in Git.
const focusPath = 'packages/focus/package.json'
const focus = JSON.parse(readFileSync(focusPath, 'utf8'))
if (focus.name !== '@sentropic/focus' || !new RegExp(`^${triple}(-rc\\.(0|[1-9]\\d*))?$`).test(focus.version)) {
  throw new Error('focus must have its own valid release version')
}
const focusBase = focus.version.split('-')[0]
const packageVersions = releaseVersion => ({
  ...Object.fromEntries(names.map(name => ['@sentropic/' + name, releaseVersion])),
  '@sentropic/focus': focusBase + releaseVersion.slice(releaseVersion.split('-')[0].length),
})
const packages = packageVersions(version)

const versionedAllowlist = new Set([
  'package.json',
  'package-lock.json',
  'packages/h2a/package.json',
  'packages/h2a-cli/package.json',
  'packages/h2a-runtime/package.json',
  'packages/track/package.json',
  'packages/h2a/.claude-plugin/plugin.json',
  'packages/h2a/.codex-plugin/plugin.json',
  'packages/h2a/registry/entries.v1.json',
  'packages/track/registry/entries.v1.json',
  'packages/h2a/src/registry/shipped-entry-digests.ts',
  'scripts/smoke-artifact.mjs'
])

function canonicalJson(value) {
  if (value === null || typeof value === 'boolean' || typeof value === 'string') return JSON.stringify(value)
  if (typeof value === 'number') return Object.is(value, -0) ? '0' : JSON.stringify(value)
  if (Array.isArray(value)) return `[${value.map((item) => canonicalJson(item)).join(',')}]`
  if (typeof value === 'object') {
    const keys = Object.keys(value).sort()
    return `{${keys.map((key) => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(',')}}`
  }
  throw new Error(`non-JSON value of type ${typeof value}`)
}

function updateShippedEntriesForVersion(releaseVersion) {
  const specs = [
    ['packages/h2a/registry/entries.v1.json', releaseVersion],
    ['packages/track/registry/entries.v1.json', releaseVersion]
  ]
  const records = []
  for (const [rel, ver] of specs) {
    if (!existsSync(rel)) continue
    const wrapper = JSON.parse(readFileSync(rel, 'utf8'))
    const entry = wrapper?.entries?.[0]
    if (!entry?.publisher) continue
    entry.publisher.packageVersion = ver
    writeFileSync(rel, JSON.stringify(wrapper, null, 2) + '\n')
    records.push({
      id: entry.id,
      packageName: entry.publisher.packageName,
      packageVersion: ver,
      digest: createHash('sha256').update(canonicalJson(entry), 'utf8').digest('hex')
    })
  }
  if (records.length === 2) {
    const tsPath = 'packages/h2a/src/registry/shipped-entry-digests.ts'
    if (existsSync(tsPath)) {
      const tsOut =
        '// Generated by scripts/generate-registry-entries.mjs — do not edit by hand.\n' +
        'export interface ShippedEntryDigestRecord {\n' +
        '  readonly id: string;\n' +
        '  readonly packageName: string;\n' +
        '  readonly packageVersion: string;\n' +
        '  readonly digest: string;\n' +
        '}\n\n' +
        'export const CURRENT_SHIPPED_ENTRY_DIGESTS: ReadonlyMap<string, ShippedEntryDigestRecord> = new Map([\n' +
        records
          .map(
            (rec) =>
              `  [${JSON.stringify(rec.id)}, { id: ${JSON.stringify(rec.id)}, packageName: ${JSON.stringify(rec.packageName)}, packageVersion: ${JSON.stringify(rec.packageVersion)}, digest: ${JSON.stringify(rec.digest)} }]`
          )
          .join(',\n') +
        '\n]);\n'
      writeFileSync(tsPath, tsOut)
    }
    const jsPath = 'packages/h2a/dist/registry/shipped-entry-digests.js'
    if (existsSync(jsPath)) {
      const jsOut =
        '// Generated by scripts/generate-registry-entries.mjs — do not edit by hand.\n' +
        'export const CURRENT_SHIPPED_ENTRY_DIGESTS = new Map([\n' +
        records
          .map(
            (rec) =>
              `  [${JSON.stringify(rec.id)}, { id: ${JSON.stringify(rec.id)}, packageName: ${JSON.stringify(rec.packageName)}, packageVersion: ${JSON.stringify(rec.packageVersion)}, digest: ${JSON.stringify(rec.digest)} }]`
          )
          .join(',\n') +
        '\n]);\n'
      writeFileSync(jsPath, jsOut)
    }
  }
}

function prepare() {
  const currentLockstep = checkLockstepVersions(process.cwd())
  if (currentLockstep !== base && !(rc && currentLockstep === version)) {
    throw new Error('tag base must match the lockstep release train')
  }
  const smokePath = 'scripts/smoke-artifact.mjs'
  const smoke = readFileSync(smokePath, 'utf8')
  const basePin = `const PINNED_RUNTIME_VERSION = '${base}'`
  const versionPin = `const PINNED_RUNTIME_VERSION = '${version}'`
  const hasBasePin = smoke.split(basePin).length === 2
  const hasVersionPin = rc && smoke.split(versionPin).length === 2
  if (!hasBasePin && !hasVersionPin) {
    throw new Error('smoke pin must match the release train exactly once')
  }
  const focusPin = `const PINNED_FOCUS_VERSION = '${focusBase}'`
  const focusRcPin = `const PINNED_FOCUS_VERSION = '${packages['@sentropic/focus']}'`
  if (smoke.split(focusPin).length !== 2 && !(rc && smoke.split(focusRcPin).length === 2)) {
    throw new Error('smoke focus pin must match the focus train exactly once')
  }
  if (focus.version !== focusBase) throw new Error('focus must keep its stable version in the source checkout')
  const pluginManifestRels = ['packages/h2a/.claude-plugin/plugin.json', 'packages/h2a/.codex-plugin/plugin.json']
  const hasPluginManifests = pluginManifestRels.some((rel) => existsSync(rel))
  // Check plugin content bump BEFORE CI workspace stamps manifests so unbumped RC tags cannot mask stale git plugin.json.
  if (hasPluginManifests) checkPluginContentVersionBump(process.cwd())
  if (rc) {
    for (const name of [...names, 'focus']) {
      const path = join('packages', name, 'package.json'), manifest = JSON.parse(readFileSync(path, 'utf8'))
      manifest.version = packages[manifest.name]
      for (const field of ['dependencies', 'peerDependencies', 'optionalDependencies', 'devDependencies']) {
        for (const dep of Object.keys(manifest[field] ?? {})) if (Object.hasOwn(packages, dep)) manifest[field][dep] = packages[dep]
      }
      writeFileSync(path, JSON.stringify(manifest, null, 2) + '\n')
    }
    if (hasPluginManifests) {
      for (const pluginRel of pluginManifestRels) {
        if (!existsSync(pluginRel)) throw new Error(`missing plugin manifest: ${pluginRel}`)
        const pluginManifest = JSON.parse(readFileSync(pluginRel, 'utf8'))
        pluginManifest.version = packages['@sentropic/h2a']
        writeFileSync(pluginRel, JSON.stringify(pluginManifest, null, 2) + '\n')
      }
    }
    updateShippedEntriesForVersion(version)
    let nextSmoke = smoke
    if (hasBasePin) nextSmoke = nextSmoke.replace(basePin, versionPin)
    if (nextSmoke.includes(focusPin)) nextSmoke = nextSmoke.replace(focusPin, focusRcPin)
    writeFileSync(smokePath, nextSmoke)
  }
  appendFileSync(process.env.GITHUB_ENV, `RELEASE_VERSION=${version}\nRELEASE_TAG=${tag}\nFOCUS_RELEASE_VERSION=${packages['@sentropic/focus']}\n`)
  console.log(`Prepared ${version}; registry tag: ${rc ? 'next' : 'latest/backfill'}`)
}

function context() {
  if (!/^[\w.-]+\/[\w.-]+$/.test(repository ?? '') ||
      !/^[1-9]\d*$/.test(process.env.GITHUB_RUN_ID ?? '') ||
      !/^[1-9]\d*$/.test(process.env.GITHUB_RUN_ATTEMPT ?? '')) throw new Error('missing CI repository/run identity')
}

function attest() {
  context()
  if (rc) {
    if (process.env.RC_SMOKE_PASSED !== 'true') throw new Error('RC post-publish install smoke must actually pass before attestation')
    for (const [name, packageVersion] of Object.entries(packages)) {
      if (JSON.parse(command('npm', ['view', name, 'dist-tags.next', '--json'])) !== packageVersion) {
        throw new Error(`${name}: next must point to ${packageVersion} before attestation`)
      }
      // An idempotent skip must not certify bytes published from another tree.
      const bytes = readFileSync(join('dist-tarballs', `sentropic-${name.slice('@sentropic/'.length)}-${packageVersion}.tgz`))
      const integrity = 'sha512-' + createHash('sha512').update(bytes).digest('base64')
      if (JSON.parse(command('npm', ['view', `${name}@${packageVersion}`, 'dist.integrity', '--json'])) !== integrity) {
        throw new Error(`${name}: registry integrity differs from the verify-built RC tarball`)
      }
    }
  }
  const record = { schema: 1, kind: rc ? 'rc' : 'stable', repository,
    runId: process.env.GITHUB_RUN_ID, runAttempt: process.env.GITHUB_RUN_ATTEMPT,
    version, sourceSha: command('git', ['rev-parse', 'HEAD']), sourceTree: tree(),
    registryTag: rc ? 'next' : 'latest/backfill', smokePassed: process.env.RC_SMOKE_PASSED === 'true', packages }
  mkdirSync('release-attestation', { recursive: true })
  writeFileSync('release-attestation/attestation.json', JSON.stringify(record, null, 2) + '\n')
  console.log(`Recorded ${record.kind} attestation for run ${record.runId}, tree ${record.sourceTree}`)
}

function applyVersionOnlyDelta(rel, rcBytes, candidateVer, targetVer) {
  if (rel === 'scripts/smoke-artifact.mjs') {
    const candidateFocus = packageVersions(candidateVer)['@sentropic/focus']
    const targetFocus = packageVersions(targetVer)['@sentropic/focus']
    return rcBytes
      .replace(`const PINNED_RUNTIME_VERSION = '${candidateVer}'`, `const PINNED_RUNTIME_VERSION = '${targetVer}'`)
      .replace(`const PINNED_FOCUS_VERSION = '${candidateFocus}'`, `const PINNED_FOCUS_VERSION = '${targetFocus}'`)
  }
  if (rel === 'packages/h2a/.claude-plugin/plugin.json' || rel === 'packages/h2a/.codex-plugin/plugin.json') {
    const parsed = JSON.parse(rcBytes)
    parsed.version = targetVer
    return JSON.stringify(parsed, null, 2) + '\n'
  }
  if (rel.endsWith('entries.v1.json')) {
    const parsed = JSON.parse(rcBytes)
    if (parsed?.entries?.[0]?.publisher) parsed.entries[0].publisher.packageVersion = targetVer
    return JSON.stringify(parsed, null, 2) + '\n'
  }
  if (rel === 'packages/h2a/src/registry/shipped-entry-digests.ts') {
    const records = []
    for (const entryRel of ['packages/h2a/registry/entries.v1.json', 'packages/track/registry/entries.v1.json']) {
      if (!existsSync(entryRel)) return null
      const entry = JSON.parse(readFileSync(entryRel, 'utf8'))?.entries?.[0]
      if (!entry?.publisher) return null
      records.push({
        id: entry.id,
        packageName: entry.publisher.packageName,
        packageVersion: entry.publisher.packageVersion,
        digest: createHash('sha256').update(canonicalJson(entry), 'utf8').digest('hex')
      })
    }
    return (
      '// Generated by scripts/generate-registry-entries.mjs — do not edit by hand.\n' +
      'export interface ShippedEntryDigestRecord {\n' +
      '  readonly id: string;\n' +
      '  readonly packageName: string;\n' +
      '  readonly packageVersion: string;\n' +
      '  readonly digest: string;\n' +
      '}\n\n' +
      'export const CURRENT_SHIPPED_ENTRY_DIGESTS: ReadonlyMap<string, ShippedEntryDigestRecord> = new Map([\n' +
      records
        .map(
          (rec) =>
            `  [${JSON.stringify(rec.id)}, { id: ${JSON.stringify(rec.id)}, packageName: ${JSON.stringify(rec.packageName)}, packageVersion: ${JSON.stringify(rec.packageVersion)}, digest: ${JSON.stringify(rec.digest)} }]`
        )
        .join(',\n') +
      '\n]);\n'
    )
  }
  if (rel.endsWith('package.json')) {
    const parsed = JSON.parse(rcBytes)
    parsed.version = targetVer
    for (const field of ['dependencies', 'peerDependencies']) {
      for (const dep of ['@sentropic/h2a', '@sentropic/h2a-cli', '@sentropic/track', '@sentropic/h2a-runtime']) {
        if (parsed[field] && Object.hasOwn(parsed[field], dep)) parsed[field][dep] = targetVer
      }
    }
    return JSON.stringify(parsed, null, 2) + '\n'
  }
  if (rel === 'package-lock.json') {
    const parsed = JSON.parse(rcBytes)
    parsed.version = targetVer
    for (const key of ['', 'packages/h2a', 'packages/h2a-cli', 'packages/h2a-runtime', 'packages/track']) {
      const pkg = parsed.packages?.[key]
      if (!pkg) continue
      pkg.version = targetVer
      for (const field of ['dependencies', 'peerDependencies']) {
        for (const dep of ['@sentropic/h2a', '@sentropic/h2a-cli', '@sentropic/track', '@sentropic/h2a-runtime']) {
          if (pkg[field] && Object.hasOwn(pkg[field], dep)) pkg[field][dep] = targetVer
        }
      }
    }
    return JSON.stringify(parsed, null, 2) + '\n'
  }
  return null
}

function isVersionManifestOnlyPromotion(api, runHeadSha, headSha, candidateVer, targetVer) {
  try {
    const cmp = api(`repos/${repository}/compare/${runHeadSha}...${headSha}`)
    if (!cmp || (cmp.status !== 'ahead' && cmp.status !== 'identical')) return false
    if (!Array.isArray(cmp.files) || cmp.files.length === 0) return false
    for (const file of cmp.files) {
      if (file.status !== 'modified' || !versionedAllowlist.has(file.filename)) return false
      const rcBlob = api(`repos/${repository}/contents/${file.filename}?ref=${runHeadSha}`)
      if (!rcBlob || typeof rcBlob.content !== 'string') return false
      const rcText = Buffer.from(rcBlob.content, 'base64').toString('utf8')
      const transformed = applyVersionOnlyDelta(file.filename, rcText, candidateVer, targetVer)
      if (transformed === null || !existsSync(file.filename) || readFileSync(file.filename, 'utf8') !== transformed) {
        return false
      }
    }
    return true
  } catch {
    return false
  }
}

function requireRc() {
  if (rc) { console.log('RC publication does not require an earlier candidate'); return }
  context()
  const sourceTree = tree()
  const headSha = command('git', ['rev-parse', 'HEAD'])
  // Repository-scoped workflow API, not caller-supplied files or PR artifacts.
  // Paginate so an unrelated later release cannot hide a still-valid proof.
  const api = path => JSON.parse(command('gh', ['api', path]))
  const pages = path => JSON.parse(command('gh', ['api', '--paginate', '--slurp', path]))
  const runs = pages(`repos/${repository}/actions/workflows/release.yml/runs?event=push&status=success&per_page=100`).flatMap(page => page.workflow_runs)
  for (const run of runs) {
    const candidate = run.head_branch?.replace(/^v/, '')
    if (run.event !== 'push' || run.status !== 'completed' || run.conclusion !== 'success' ||
        run.path !== '.github/workflows/release.yml' || run.head_repository?.full_name !== repository ||
        run.head_branch !== `v${candidate}` ||
        !new RegExp(`^${base.replaceAll('.', '\\.')}\\-rc\\.(0|[1-9]\\d*)$`).test(candidate ?? '') ||
        !/^[1-9]\d*$/.test(String(run.id)) || !/^[1-9]\d*$/.test(String(run.run_attempt)) ||
        !/^[a-f0-9]{40}$/.test(run.head_sha ?? '')) continue
    const artifacts = pages(`repos/${repository}/actions/runs/${run.id}/artifacts?per_page=100`).flatMap(page => page.artifacts)
      .filter(artifact => artifact.name === `release-attestation-${run.run_attempt}` && artifact.expired === false &&
        artifact.workflow_run?.id === run.id && artifact.workflow_run?.head_sha === run.head_sha)
    if (artifacts.length !== 1) continue
    const dir = mkdtempSync(join(tmpdir(), 'release-rc-proof-'))
    try {
      command('gh', ['run', 'download', String(run.id), '--repo', repository,
        '--name', artifacts[0].name, '--dir', dir])
      const record = JSON.parse(readFileSync(join(dir, 'attestation.json'), 'utf8'))
      const rcTreeSha = api(`repos/${repository}/git/commits/${run.head_sha}`).tree?.sha
      const treeMatched = rcTreeSha === sourceTree ||
        isVersionManifestOnlyPromotion(api, run.head_sha, headSha, candidate, base)
      const expected = { schema: 1, kind: 'rc', repository, runId: String(run.id), runAttempt: String(run.run_attempt),
        version: candidate, sourceSha: run.head_sha, sourceTree: record?.sourceTree, registryTag: 'next', smokePassed: true,
        packages: packageVersions(candidate) }
      if (!treeMatched || !rcTreeSha || record?.sourceTree !== rcTreeSha || !isDeepStrictEqual(record, expected)) continue
      console.log(`Accepted RC run ${run.id}: ${candidate}, RC tree ${rcTreeSha}${rcTreeSha === sourceTree ? '' : ` -> stable ${sourceTree} (version-manifest-only promotion)`}`)
      return
    } finally { rmSync(dir, { recursive: true, force: true }) }
  }
  throw new Error(`No successful RC attestation for ${base} with source tree ${sourceTree}; refusing stable publication (including backfills)`)
}

switch (process.argv[2]) {
  case 'prepare': prepare(); break
  case 'attest': attest(); break
  case 'require-rc': requireRc(); break
  default: throw new Error('expected prepare, require-rc or attest')
}

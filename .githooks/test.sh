#!/usr/bin/env bash
# End-to-end test for the commit-msg guard and worktree-safe installer.
# Uses a disposable sandbox under TMPDIR / RUNNER_TEMP / $HOME/.cache-tmp (never bare /tmp).
# Run: bash .githooks/test.sh
set -uo pipefail
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

hook_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
hook="$hook_dir/commit-msg"
tmp_base="${TMPDIR:-${RUNNER_TEMP:-$HOME/.cache-tmp/h2a-test}}"
mkdir -p "$tmp_base"
sandbox="$(mktemp -d "$tmp_base/hook-test.XXXXXX")"
trap 'rm -rf "$sandbox"' EXIT

git init -q "$sandbox/repo"
git -C "$sandbox/repo" config core.hooksPath "$hook_dir"
git -C "$sandbox/repo" config user.email "test@example.com"
git -C "$sandbox/repo" config user.name "hook test"
git -C "$sandbox/repo" commit -q --allow-empty --no-verify -m "baseline"
base="$(git -C "$sandbox/repo" rev-parse HEAD)"

fail=0
try_commit() {
  printf '%s\n' "$RANDOM" > "$sandbox/repo/f"
  git -C "$sandbox/repo" add f
  git -C "$sandbox/repo" commit -m "$1" 2>"$sandbox/err"
}
expect_blocked() {
  if try_commit "$2"; then
    echo "FAIL [$1]: commit ACCEPTED"
    fail=1
    git -C "$sandbox/repo" reset -q --hard "$base"
    return
  fi
  grep -q 'commit blocked' "$sandbox/err" || { echo "FAIL [$1]: blocked without expected message"; fail=1; }
  [ "$(git -C "$sandbox/repo" rev-parse HEAD)" = "$base" ] || { echo "FAIL [$1]: HEAD moved"; fail=1; }
  echo "ok   [$1]: blocked"
}
expect_allowed() {
  if try_commit "$2"; then
    echo "ok   [$1]: allowed"
    git -C "$sandbox/repo" reset -q --hard "$base"
  else
    echo "FAIL [$1]: clean commit BLOCKED"
    cat "$sandbox/err"
    fail=1
  fi
}
expect_hook_allows() {
  if "$hook" "$2" >/dev/null 2>&1; then
    echo "ok   [$1]: allowed"
  else
    echo "FAIL [$1]: blocked a clean message"
    fail=1
  fi
}

# One real commit per trailer / AI marker branch (case-insensitive):
expect_blocked "Claude Co-Authored-By trailer"    "$(printf 'feat: x\n\nCo-Authored-By: Claude Opus 4.8 <noreply@anthropic.com>')"
expect_blocked "Codex Co-Authored-By trailer"     "$(printf 'feat: x\n\nCo-Authored-By: Codex <noreply@openai.com>')"
expect_blocked "Codex alt email trailer"          "$(printf 'feat: x\n\nCo-Authored-By: Codex <codex@openai.com>')"
expect_blocked "Muse Code Co-authored-by trailer" "$(printf 'feat: x\n\nCo-authored-by: Muse Code <muse@example.com>')"
expect_blocked "Mistral Vibe Co-Authored-By"      "$(printf 'feat: x\n\nCo-Authored-By: Mistral Vibe <vibe@mistral.ai>')"
expect_blocked "Mistral Vibe Generated by line"   "$(printf 'feat: x\n\nGenerated by Mistral Vibe.')"
expect_blocked "lowercase co-authored-by"         "$(printf 'feat: x\n\nco-authored-by: some bot <bot@example.com>')"
expect_blocked "Claude-Session trailer"           "$(printf 'feat: x\n\nClaude-Session: https://claude.ai/code/session_01ABC')"
expect_blocked "naked claude session url"         "$(printf 'feat: x\n\nhttps://claude.ai/code/session_01ABC')"
expect_blocked "generated-with-claude"            "$(printf 'feat: x\n\nGenerated with [Claude Code]')"
expect_blocked "generated-with-vibe lowercase"    "$(printf 'feat: x\n\ngenerated with mistral vibe')"
expect_blocked "claude.com/claude-code url"       "$(printf 'feat: x\n\nsee https://claude.com/claude-code for details')"
expect_blocked "robot marker"                     "$(printf 'feat: x\n\n\xf0\x9f\xa4\x96 automated')"

# Clean messages that MUST pass:
expect_allowed "plain message"                    "chore: routine change"
expect_allowed "prose mentions co-authored-by"    "docs: reject Co-authored-by: trailers in commit messages"
expect_allowed "prose mentions claude-session"    "docs: strip Claude-Session: lines from history"
expect_allowed "Signed-off-by human trailer"      "$(printf 'chore: sign off\n\nSigned-off-by: Jane Doe <jane@example.com>')"
scissors="$sandbox/scissors.txt"
printf 'docs: edit\n\n# ------------------------ >8 ------------------------\n+Co-Authored-By: Claude <x@y.z>\n' > "$scissors"
expect_hook_allows "commit -v diff quoting a trailer" "$scissors"

# Strip mode removes offending trailer lines and allows the cleaned commit:
printf '%s\n' "$RANDOM" > "$sandbox/repo/f"
git -C "$sandbox/repo" add f
if H2A_TRAILER_GUARD_MODE=strip git -C "$sandbox/repo" commit -m "$(printf 'feat: strip test\n\nBody line.\n\nCo-Authored-By: Mistral Vibe <vibe@mistral.ai>\nClaude-Session: https://claude.ai/code/session_01XYZ')" 2>"$sandbox/err"; then
  msg="$(git -C "$sandbox/repo" log -1 --format='%B')"
  if printf '%s' "$msg" | grep -iEq 'co-authored-by|claude-session'; then
    echo "FAIL [strip mode]: trailer remained in committed message"
    fail=1
  elif printf '%s' "$msg" | grep -q 'Body line.'; then
    echo "ok   [strip mode]: stripped trailers and preserved body"
  else
    echo "FAIL [strip mode]: body lost"
    fail=1
  fi
  git -C "$sandbox/repo" reset -q --hard "$base"
else
  echo "FAIL [strip mode]: commit rejected in strip mode"
  cat "$sandbox/err"
  fail=1
fi

# Worktree-safe local install covers linked worktrees even on branches without .githooks:
repo_wt="$sandbox/wt-origin"
git init -q "$repo_wt"
git -C "$repo_wt" config user.email t@example.com
git -C "$repo_wt" config user.name t
git -C "$repo_wt" commit -q --allow-empty --no-verify -m "root"
(cd "$repo_wt" && bash "$hook_dir/install.sh" --local >/dev/null)
git -C "$repo_wt" worktree add -q -b other-branch "$sandbox/wt-linked"
printf '1\n' > "$sandbox/wt-linked/a.txt"
git -C "$sandbox/wt-linked" add a.txt
if git -C "$sandbox/wt-linked" commit -m "$(printf 'feat: wt\n\nCo-Authored-By: Claude Opus 4.8 <noreply@anthropic.com>')" 2>/dev/null; then
  echo "FAIL [worktree-safe install]: trailer commit ACCEPTED in linked worktree"
  fail=1
else
  echo "ok   [worktree-safe install]: blocked in linked worktree without .githooks"
fi

# Global install gates a repo that never configured a local hook:
gc="$sandbox/global-config"
git config --file "$gc" core.hooksPath "$hook_dir"
repo2="$sandbox/repo2"
git init -q "$repo2"
run2() { GIT_CONFIG_GLOBAL="$gc" GIT_CONFIG_SYSTEM=/dev/null git -C "$repo2" "$@"; }
run2 config user.email t@example.com
run2 config user.name t
run2 commit -q --allow-empty --no-verify -m baseline
printf '1\n' > "$repo2/f"
run2 add f
if run2 commit -m "$(printf 'feat: z\n\nCo-Authored-By: Claude Opus 4.8 <noreply@anthropic.com>')" 2>/dev/null; then
  echo "FAIL [global gates a hook-less repo]: co-authored commit ACCEPTED"
  fail=1
else
  echo "ok   [global gates a hook-less repo]: blocked"
fi

if [ "$fail" -eq 0 ]; then
  echo "ALL PASS — every runtime path and worktree is gated; clean messages pass."
  exit 0
fi
echo "TESTS FAILED"
exit 1
